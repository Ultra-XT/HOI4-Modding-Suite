// Regression (bug-hunt #21 — final-coverage workflow, research-server finder; verifier died on a session
// limit so this was adjudicated by hand): serializeTechnology regenerates a parent's `path = {
// leads_to_tech = X }` edges purely by scanning the catalog for CHILDREN whose prerequisites name the
// parent (computeOutgoingPaths). DEPENDENCY-mod children exist in the save-time catalog only as id stubs
// `{ id, isMod:false }` with NO prerequisites (dep files aren't parsed into the inversion), so a
// hand-authored `path = { leads_to_tech = <dep_tech> }` in the active mod was silently DROPPED whenever
// its parent tech was re-saved (moved/edited). FIX: after the child-side scan, union the parent's own
// leadsTo targets whose catalog entry has NO prerequisites array (the "child side unknowable" stubs).
// Invariants preserved: an EDITABLE child carries a prerequisites ARRAY (even empty), so removing a link
// in the editor still removes the path.
//
// ⚠️ UPDATED 2026-09-02 (#dangling-path-deleted): "a DELETED tech is absent from the catalog, so its edge
// stays dropped" was the deletion contract AND, unintentionally, a rule that deleted any edge naming a
// technology nothing defines — 84 of those across the installed mods. The deletion signal is now explicit
// (the save endpoint strips a successfully-deleted id from leadsTo), so absence from the catalog no longer
// means "deleted". Cases 4 and 4b pin both halves.
// Run: node test-tech-dep-path-preserve.js
"use strict";
const S = require("./server.js");
S.createApp(); // serializeTechnology lives in the app closure; the export ref is populated on createApp()
let pass = 0, fail = 0;
const ok = (n, c, x) => { if (c) { pass++; console.log("  PASS", n); } else { fail++; console.log("  FAIL", n, x != null ? "→ " + JSON.stringify(String(x).slice(0, 200)) : ""); } };

const PARENT = {
  id: "my_parent", isMod: true, name: "Parent", fileName: "custom_technologies.txt",
  folder: "infantry_folder", x: 0, y: 0, researchCost: 1, startYear: 1936,
  leadsTo: ["md_dep_child"], prerequisites: [], enableEquipments: [], mutuallyExclusive: [], subTechnologies: [],
};

// (1) THE BUG: dep-mod child = catalog stub without prerequisites → edge must now be PRESERVED from leadsTo
{
  const catalog = [PARENT, { id: "md_dep_child", isMod: false }];
  const out = S.serializeTechnology(PARENT, catalog);
  ok("path to DEP-MOD child preserved from leadsTo", /leads_to_tech = md_dep_child/.test(out), out.slice(0, 300));
  ok("exactly one path block (no duplication)", (out.match(/leads_to_tech = md_dep_child/g) || []).length === 1, out);
}

// (2) editable child with the prereq → edge regenerated by the child-side scan, and NOT duplicated by the union
{
  const child = { id: "md_dep_child", isMod: true, prerequisites: [{ type: "AND", tech: "my_parent" }] };
  const out = S.serializeTechnology(PARENT, [PARENT, child]);
  ok("editable child's edge emitted once (scan + union dedupe)", (out.match(/leads_to_tech = md_dep_child/g) || []).length === 1, out);
}

// (3) LINK REMOVAL stays authoritative: editable child with EMPTY prereqs array → stale leadsTo must NOT re-add
{
  const child = { id: "md_dep_child", isMod: true, prerequisites: [] };
  const out = S.serializeTechnology(PARENT, [PARENT, child]);
  ok("removed link NOT resurrected from stale leadsTo (empty prereq ARRAY is authoritative)", !/leads_to_tech/.test(out), out);
}

// (4) THE DELETION CONTRACT MOVED UP A LAYER — #dangling-path-deleted.
//
// This used to read "absent from the catalog → edge stays dropped", and that single rule was carrying TWO
// jobs at once: removing a DELETED technology's incoming edges, and, by accident, deleting any
// `leads_to_tech` naming a technology nothing defines. The second is the author's own text. Measured across
// the installed corpora: 84 such edges, 61 of them in Novum Vexillum, all silently removed by a no-edit save
// of a file the modder had not touched.
//
// So the deletion signal is now EXPLICIT rather than inferred: /api/technologies/save-batch strips a deleted
// id from every payload tech's leadsTo (and pathMeta) before serialization — and only for a deletion whose
// block was actually removed, since a refused deletion leaves the technology on disk. What reaches the
// serializer with an unknown target is therefore an authored dangling edge, and is kept.
{
  const out = S.serializeTechnology(PARENT, [PARENT]);
  ok("an authored edge to a tech nothing defines is PRESERVED",
    /leads_to_tech = md_dep_child/.test(out), out.slice(0, 200));
}

// (4b) …and the deletion contract itself, at the level it now lives: the endpoint clears leadsTo, so there
// is nothing left to emit. This is the half that must never regress — a parent keeping a path to a deleted
// technology is a dangling edge HOI4 logs as "undefined technology".
{
  const afterEndpointStrip = { ...PARENT, leadsTo: [] };
  const out = S.serializeTechnology(afterEndpointStrip, [afterEndpointStrip]);
  ok("a DELETED tech's edge is gone once the endpoint strips it from leadsTo", !/leads_to_tech/.test(out), out);
}

// (5) no leadsTo at all → no path blocks (baseline)
{
  const p2 = { ...PARENT, leadsTo: [] };
  const out = S.serializeTechnology(p2, [p2, { id: "md_dep_child", isMod: false }]);
  ok("no leadsTo → no path blocks", !/leads_to_tech/.test(out), out);
}

console.log(`\nTECH-DEP-PATH-PRESERVE: ${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
