// ai-vocab.js — loads the bundled HOI4 token spec (data/hoi4-spec.json) and builds the
// authoritative command-vocabulary block appended to AI system prompts.
//
// The spec is derived from the CWTools HOI4 config (MIT) by scripts/build-hoi4-spec.cjs.
// Feeding the AI the COMPLETE set of valid effect/trigger/modifier names stops it inventing
// commands that don't exist (beyond the hand-written cheat sheet). Degrades to a no-op empty
// block if data/hoi4-spec.json is missing, so the app still works without it.
const fs = require("fs");
const path = require("path");

let _spec = null;
function loadSpec() {
  if (_spec) return _spec;
  const empty = { effects: [], triggers: [], modifiers: [], _meta: { counts: { effects: 0, triggers: 0, modifiers: 0 } } };
  try {
    const p = path.join(__dirname, "data", "hoi4-spec.json");
    if (!fs.existsSync(p)) {
      _spec = empty;
    } else {
      const parsed = JSON.parse(fs.readFileSync(p, "utf8"));
      _spec = {
        effects: Array.isArray(parsed.effects) ? parsed.effects : [],
        triggers: Array.isArray(parsed.triggers) ? parsed.triggers : [],
        modifiers: Array.isArray(parsed.modifiers) ? parsed.modifiers : [],
        _meta: parsed._meta || empty._meta,
      };
    }
  } catch (e) {
    _spec = empty;
  }
  return _spec;
}

let _block;
function getHoi4VocabBlock() {
  if (_block !== undefined) return _block;
  const spec = loadSpec();
  // Take only entries that actually carry a name. `.map((e) => e.name)` alone turns a malformed entry into
  // the literal string "undefined" in the middle of a comma-separated list the prompt introduces as "the
  // COMPLETE set of valid names" — so the AI would be told, authoritatively, that a command called
  // `undefined` exists. The bundled spec is clean today (0 nameless entries across 538 effects, 566
  // triggers and 812 modifiers), but it is generated by a script from an external config, and this block
  // goes into every AI prompt, so a bad regeneration should not be able to poison the grounding.
  const names = (arr) => (Array.isArray(arr) ? arr : [])
    .map((x) => (x && typeof x.name === "string" ? x.name.trim() : ""))
    .filter(Boolean);
  const eff = names(spec.effects);
  const trg = names(spec.triggers);
  const mod = names(spec.modifiers);
  if (!eff.length && !trg.length && !mod.length) {
    _block = "";
    return _block;
  }
  _block =
    "\n\n### AUTHORITATIVE HOI4 COMMAND VOCABULARY" +
    " (the COMPLETE set of valid names — if a command is NOT in these lists it DOES NOT EXIST;" +
    " pick the closest valid name, never invent one):\n" +
    `EFFECTS (valid inside effect / reward / immediate blocks): ${eff.join(", ")}\n\n` +
    `TRIGGERS & CONDITIONS (valid inside limit / if / available / allowed): ${trg.join(", ")}\n\n` +
    `MODIFIER KEYS (valid inside modifier = { } and add_*_modifier blocks): ${mod.join(", ")}\n`;
  return _block;
}

// test seam: let a test reset the memoized block after pointing at a fixture
function _reset() {
  _spec = null;
  _block = undefined;
}

module.exports = { loadSpec, getHoi4VocabBlock, _reset };
