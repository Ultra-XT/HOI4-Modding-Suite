// test-ai-vocab.js — the AI grounding vocabulary block must load the shipped spec and contain
// real command names (so the AI is told the authoritative vocabulary, not left to invent it).
const { loadSpec, getHoi4VocabBlock } = require("./ai-vocab");

let failed = 0;
function ok(cond, msg) {
  if (cond) console.log("  ok  " + msg);
  else {
    console.error("  FAIL " + msg);
    failed++;
  }
}

const spec = loadSpec();
ok(spec.effects.length > 400, `spec loaded effects (${spec.effects.length})`);
ok(spec.triggers.length > 400, `spec loaded triggers (${spec.triggers.length})`);
ok(spec.modifiers.length > 500, `spec loaded modifiers (${spec.modifiers.length})`);

const block = getHoi4VocabBlock();
ok(typeof block === "string" && block.length > 1000, "vocab block is a non-trivial string");
ok(/AUTHORITATIVE HOI4 COMMAND VOCABULARY/.test(block), "vocab block has the heading");
// real tokens must appear so the AI is actually grounded
for (const n of ["add_stability", "set_country_flag", "annex_country"])
  ok(block.includes(n), `vocab block lists effect "${n}"`);
for (const n of ["has_country_flag", "has_war"]) ok(block.includes(n), `vocab block lists trigger "${n}"`);
for (const n of ["army_attack_factor", "political_power_gain"])
  ok(block.includes(n), `vocab block lists modifier "${n}"`);
// must NOT contain leftover placeholder junk
ok(!block.includes("<scripted_effect>"), "vocab block has no <placeholder> junk");

// memoized: second call returns the same string instance (cheap, built once)
ok(getHoi4VocabBlock() === block, "vocab block is memoized");

// ── a malformed entry must never become a command ────────────────────────────────────────────────
//
// This block introduces itself to the model as "the COMPLETE set of valid names — if a command is NOT in
// these lists it DOES NOT EXIST". Mapping entries straight to `.name` turned a nameless entry into the
// literal string "undefined" inside that list, so the AI would be told, authoritatively, that a command
// called `undefined` exists — in the one place whose entire job is to stop it inventing commands.
//
// The shipped spec is clean, and that is asserted first so a bad regeneration is caught on its own. But the
// spec is GENERATED by scripts/build-hoi4-spec.cjs from an external config, so the block must also be
// unable to emit junk if that ever produces a malformed entry.
ok([...spec.effects, ...spec.triggers, ...spec.modifiers]
  .every((e) => e && typeof e.name === "string" && e.name.trim()), "every shipped spec entry has a name");
ok(!/(^|[,\s])undefined([,\s]|$)/.test(block), "vocab block presents no \"undefined\" command");

// The degradation paths are exercised by patching fs in place rather than by moving data/hoi4-spec.json:
// a test that renames the real spec and then throws would leave the app with no vocabulary at all.
const fs = require("fs");
const { _reset } = require("./ai-vocab");
function withSpec(payload, fn) {
  const realExists = fs.existsSync, realRead = fs.readFileSync;
  fs.existsSync = (p) => (String(p).includes("hoi4-spec.json") ? payload !== null : realExists(p));
  fs.readFileSync = (p, enc) => (String(p).includes("hoi4-spec.json") ? payload : realRead(p, enc));
  try { _reset(); fn(); } finally { fs.existsSync = realExists; fs.readFileSync = realRead; _reset(); }
}

withSpec(JSON.stringify({
  effects: [{ name: "real_effect" }, { name: "" }, { name: "  " }, { notName: "x" }, null, { name: 42 }],
  triggers: [{ name: "real_trigger" }],
  modifiers: [{ name: "real_modifier" }],
}), () => {
  const b = getHoi4VocabBlock();
  ok(/real_effect/.test(b) && /real_trigger/.test(b) && /real_modifier/.test(b), "good names survive a malformed spec");
  ok(!/undefined/.test(b), "a nameless entry does not become \"undefined\"");
  ok(!/(^|[,\s])42([,\s]|$)/.test(b), "a non-string name is dropped rather than printed");
  const effLine = (b.match(/EFFECTS[^\n]*\n/) || [""])[0];
  ok(!/,\s*,/.test(effLine) && !/:\s*,/.test(effLine), "dropped entries leave no dangling commas");
});

// ── the app must still work with no spec at all ──────────────────────────────────────────────────
withSpec(null, () => {
  ok(loadSpec().effects.length === 0, "a missing spec file yields empty lists rather than throwing");
  ok(getHoi4VocabBlock() === "", "…and an empty block, so prompts simply lose the vocabulary");
});
withSpec("{ this is not json", () => {
  ok(loadSpec().effects.length === 0, "malformed JSON yields empty lists rather than throwing");
  ok(getHoi4VocabBlock() === "", "…and an empty block");
});
withSpec(JSON.stringify({ effects: "not an array", triggers: null }), () => {
  ok(loadSpec().effects.length === 0 && loadSpec().triggers.length === 0, "a wrong-shaped spec yields empty lists");
});

// _reset has to genuinely clear the memo, or the checks above would have been reading the real block.
withSpec(JSON.stringify({ effects: [{ name: "sentinel_effect" }], triggers: [], modifiers: [] }), () => {
  ok(/sentinel_effect/.test(getHoi4VocabBlock()), "_reset lets a different spec take effect");
});
ok(/add_stability/.test(getHoi4VocabBlock()), "the real vocabulary is restored afterwards");

if (failed) {
  console.error(`\ntest-ai-vocab: ${failed} check(s) FAILED`);
  process.exit(1);
}
console.log("\ntest-ai-vocab: all checks passed");
