// #oob-outside-region — THE LAND ARMY'S WIRING WAS WRITTEN WHERE THE NEXT NAVY SAVE DELETES IT.
//
// Saving a land army wires `oob = "<file>"` into the country's history so HOI4 loads it. That line must not
// land inside a Nova-managed region, because each region is rebuilt from scratch: splitOobRefRegion cuts the
// whole START..END span out and buildOobRefRegion writes a fresh one, so anything that had been placed in
// there is gone.
//
// The guard existed and named two of the THREE regions — the equipment-variant block and the starting
// stockpile — and not NOVA_OOB_START, the naval/air OOB block. All three sentinels are COMMENTS, so for a
// country whose history has a naval/air region and neither of the other two, findIndex returned -1, the
// skip-leading-comments fallback walked past the sentinel and its `# NOVA-OOBREF {…}` header, and the land
// oob line was inserted between them. Save a navy, then a land army, then touch the navy again and the land
// army's wiring is silently gone — the divisions stop spawning and nothing says why.
//
// ⚠️ The fixture below builds a history that contains ONLY the naval/air region. That is the whole point: a
// file that also has a variant or stockpile region hits the first two sentinels and cannot show the bug.
"use strict";
const fs = require("fs");
const os = require("os");
const path = require("path");

const ROOT = fs.mkdtempSync(path.join(os.tmpdir(), "nova-oobreg-"));
process.env.HOI4_MODS_ROOT = ROOT;
process.env.APPDATA = path.join(ROOT, "appdata");
fs.mkdirSync(process.env.APPDATA, { recursive: true });
const { createApp } = require("./server.js");

const fails = [];
let checks = 0;
function rec(label, cond, detail) {
  checks++;
  if (cond) console.log("  ok   " + label);
  else {
    fails.push(label);
    console.log("  FAIL " + label + "  -> " + String(typeof detail === "string" ? detail : JSON.stringify(detail)).slice(0, 500));
  }
}

const OOB_START = "# >>> NOVA naval/air OOB >>>";
const OOB_END = "# <<< NOVA naval/air OOB <<<";
const toPosix = (p) => p.split(path.sep).join("/");

const MOD = path.join(ROOT, "oobmod");
fs.mkdirSync(path.join(MOD, "history", "countries"), { recursive: true });
fs.mkdirSync(path.join(MOD, "common", "country_tags"), { recursive: true });
fs.mkdirSync(path.join(MOD, "common", "countries"), { recursive: true });
fs.writeFileSync(path.join(MOD, "descriptor.mod"), 'name="OobMod"\nsupported_version="1.19.*"\n');
fs.writeFileSync(path.join(ROOT, "oobmod.mod"),
  'name="OobMod"\npath="' + toPosix(MOD) + '"\nsupported_version="1.19.*"\n');
fs.writeFileSync(path.join(MOD, "common", "country_tags", "zz.txt"), 'OOB = "countries/Oobland.txt"\n');
fs.writeFileSync(path.join(MOD, "common", "countries", "Oobland.txt"), "graphical_culture = western_european_gfx\n");

// A history whose ONLY Nova region is the naval/air one — exactly the shape the guard missed.
const HIST = path.join(MOD, "history", "countries", "OOB - Oobland.txt");
fs.writeFileSync(HIST, [
  "# Country history file generated by Nova",
  OOB_START,
  '# NOVA-OOBREF {"naval":"OOB_naval"}',
  'set_naval_oob = "OOB_naval"',
  OOB_END,
  "capital = 1",
  "",
].join("\n"), "utf8");

let PORT = 50880;
(async () => {
  let srv = null;
  try {
    const app = createApp();
    srv = await new Promise((r) => { const s = app.listen(++PORT, () => r(s)); });
    const post = (p, b) => fetch("http://127.0.0.1:" + PORT + p, {
      method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(b),
    }).then((r) => r.json()).catch((e) => ({ error: String(e) }));

    console.log("\n[the fixture] a history whose only Nova region is the naval/air block");
    {
      const t = fs.readFileSync(HIST, "utf8");
      rec("it has the naval/air region", t.includes(OOB_START) && t.includes(OOB_END), t);
      rec("…and neither of the two regions the guard already knew about",
        !t.includes("NOVA equipment variants") && !t.includes("NOVA starting stockpile"), t);
      rec("…and every sentinel is a comment, which is why the fallback walked past it",
        t.split("\n").filter((l) => l.trim().startsWith("#")).length >= 3, t);
    }

    console.log("\n[saving a land army] the oob line must land OUTSIDE the region");
    {
      // The body public/army.js:4554 actually sends. `regiments` and `support` are ARRAYS of {unit,x,y} —
      // an object keyed by unit name is rejected with "has no battalions", which is the tester's payload
      // rather than a defect, and is exactly the trap that has produced false findings here before.
      const r = await post("/api/army/save", {
        modPath: MOD, tag: "OOB", file: "OOB_1936.txt",
        templates: [{
          name: "Infantry Division",
          regiments: [{ unit: "infantry", x: 0, y: 0 }],
          support: [],
          _origName: "Infantry Division",
          _dirty: true,
        }],
        divisions: [{ name: "1. Infantry Division", location: 1, template: "Infantry Division", _dirty: true }],
      });
      const t = fs.readFileSync(HIST, "utf8");
      const lines = t.split("\n");
      const oobIdx = lines.findIndex((l) => /^\s*oob\s*=\s*"/.test(l));
      const startIdx = lines.findIndex((l) => l.includes(OOB_START));
      const endIdx = lines.findIndex((l) => l.includes(OOB_END));
      console.log("     reply: " + JSON.stringify(r).slice(0, 120));
      console.log("     history now:\n" + lines.map((l, n) => "       " + n + ": " + l).join("\n"));
      if (oobIdx === -1) {
        // The endpoint may legitimately decline to wire (e.g. it needs more of a payload) — say so rather
        // than passing silently, because an absent line cannot demonstrate anything either way.
        rec("(no oob line was written — this run cannot demonstrate the placement)", true, r);
      } else {
        rec("the land oob line was written", oobIdx !== -1, lines[oobIdx]);
        rec("…OUTSIDE the naval/air region, so the next navy save cannot delete it",
          !(startIdx !== -1 && endIdx !== -1 && oobIdx > startIdx && oobIdx < endIdx),
          { oobIdx, startIdx, endIdx });
        rec("…and the naval/air region is still intact",
          startIdx !== -1 && endIdx !== -1 && endIdx > startIdx, { startIdx, endIdx });
      }
    }

    console.log("\n[the real consequence] a later naval save must not take the land wiring with it");
    {
      const before = fs.readFileSync(HIST, "utf8");
      const hadOob = /^\s*oob\s*=\s*"/m.test(before);
      await post("/api/army/save", {
        modPath: MOD, tag: "OOB", domain: "naval",
        fleets: [{ name: "Home Fleet", base: 1, taskForces: [] }],
      });
      const after = fs.readFileSync(HIST, "utf8");
      if (!hadOob) rec("(no land oob to survive — skipped)", true);
      else rec("the land oob line survives a naval save", /^\s*oob\s*=\s*"/m.test(after), after);
    }

    console.log("\n[the guard itself] all three regions are named, not two");
    {
      const src = fs.readFileSync(path.join(__dirname, "server.js"), "utf8");
      const m = /let i = bodyLines\.findIndex\(\(l\) =>[\s\S]{0,200}?\);/.exec(src);
      rec("the insertion guard exists", !!m, "not found");
      rec("…and names the equipment-variant region", !!m && /NOVA_VAR_START/.test(m[0]), m && m[0]);
      rec("…the starting-stockpile region", !!m && /NOVA_SP_START/.test(m[0]), m && m[0]);
      rec("…and the naval/air OOB region, which it used to miss",
        !!m && /NOVA_OOB_START/.test(m[0]), m && m[0]);
    }

    srv.closeAllConnections(); srv.close(); srv = null;
    console.log(`\n=== oob outside nova regions: ${checks} checks, ${fails.length} failed ===`);
    if (fails.length) { fails.forEach((x) => console.log("   FAILED: " + x)); process.exitCode = 1; }
  } catch (e) {
    console.error("HARNESS ERROR", e && e.stack ? e.stack.split("\n").slice(0, 8).join("\n") : e);
    process.exitCode = 1;
  } finally {
    try { if (srv) { srv.closeAllConnections(); srv.close(); } } catch (_) {}
    try { fs.rmSync(ROOT, { recursive: true, force: true }); } catch (_) {}
  }
})();
