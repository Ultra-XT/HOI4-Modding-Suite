// Nova only owns interface/nova_tech_icons.gfx if NOVA WROTE IT (#managed-file-ownership).
//
// Found by an adversarial sweep and confirmed live: pressing Save on the research page with ZERO
// edits deleted interface/nova_tech_icons.gfx from the mod. registerTechIconSprites() took its
// "nothing to register, tidy up the empty managed file" branch unconditionally, so an empty icon
// map — the normal state of a mod that has never picked a tech icon — unlinked whatever it found
// at that path, including a file the modder wrote themselves.
//
// Two rules are pinned here:
//   1. a file without Nova's generated header is FOREIGN — never deleted, never overwritten;
//   2. Nova's own file is only removed when the icon map is genuinely empty. If the map has entries
//      but none resolve to a texture (cold sprite cache, icon from a dependency that didn't load),
//      the previous registrations are kept — stale beats gone.
const fs = require("fs");
const os = require("os");
const path = require("path");
const assert = require("assert");

const { registerTechIconSprites } = require("./server.js");

let pass = 0;
const ok = (cond, label) => { assert.ok(cond, label); pass++; };

const mkMod = () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "nova-gfxown-"));
  fs.mkdirSync(path.join(root, "interface"), { recursive: true });
  return root;
};
const gfxOf = (root) => path.join(root, "interface", "nova_tech_icons.gfx");
const FOREIGN = [
  "spriteTypes = {",
  '\tspriteType = {',
  '\t\tname = "GFX_handmade_medium"',
  '\t\ttexturefile = "gfx/interface/technologies/handmade.dds"',
  "\t}",
  "}",
  "",
].join("\n");

// ── 1. a foreign file survives a save that registers nothing ────────────────────────────────────
{
  const root = mkMod();
  fs.writeFileSync(gfxOf(root), FOREIGN, "utf8");
  const r = registerTechIconSprites(root, {});
  ok(fs.existsSync(gfxOf(root)), "foreign nova_tech_icons.gfx must survive an empty save");
  ok(fs.readFileSync(gfxOf(root), "utf8") === FOREIGN, "foreign file must be byte-identical afterwards");
  ok(r.foreignFile === true, "the result reports that the file was left alone");
  fs.rmSync(root, { recursive: true, force: true });
}

// ── 2. a foreign file is not clobbered even when there ARE sprites to register ───────────────────
{
  const root = mkMod();
  fs.writeFileSync(gfxOf(root), FOREIGN, "utf8");
  const r = registerTechIconSprites(root, { my_tech: "GFX_some_existing_icon" });
  ok(fs.readFileSync(gfxOf(root), "utf8") === FOREIGN, "foreign file must not be overwritten by a registration");
  ok(r.registered === 0, "nothing is registered while a foreign file occupies the path");
  fs.rmSync(root, { recursive: true, force: true });
}

// ── 3. Nova's OWN file is removed when the icon map is genuinely empty ───────────────────────────
{
  const root = mkMod();
  fs.writeFileSync(gfxOf(root),
    "# Auto-generated by Nova — maps each tech to its picked research-tree icon. Safe to delete.\nspriteTypes = {\n}\n", "utf8");
  registerTechIconSprites(root, {});
  ok(!fs.existsSync(gfxOf(root)), "Nova's own file is tidied away when no icons are assigned");
  fs.rmSync(root, { recursive: true, force: true });
}

// ── 4. Nova's own file is KEPT when icons are assigned but none resolve ──────────────────────────
{
  const root = mkMod();
  const prior = "# Auto-generated by Nova — maps each tech to its picked research-tree icon. Safe to delete.\n"
    + 'spriteTypes = {\n\tspriteType = {\n\t\tname = "GFX_old_tech_medium"\n\t\ttexturefile = "gfx/interface/technologies/old.dds"\n\t}\n}\n';
  fs.writeFileSync(gfxOf(root), prior, "utf8");
  // an icon key that cannot resolve to any texture in a bare mod
  const r = registerTechIconSprites(root, { old_tech: "GFX_definitely_not_a_real_sprite_zzz" });
  ok(r.registered === 0, "an unresolvable icon registers nothing");
  ok(fs.existsSync(gfxOf(root)), "previous registrations survive a resolution miss");
  ok(fs.readFileSync(gfxOf(root), "utf8") === prior, "the kept file is unchanged");
  ok(r.keptUnresolved === true, "the result reports that the file was kept");
  fs.rmSync(root, { recursive: true, force: true });
}

// ── 5. no file at all + nothing to register = no file created ───────────────────────────────────
{
  const root = mkMod();
  registerTechIconSprites(root, {});
  ok(!fs.existsSync(gfxOf(root)), "an empty save does not create the managed file");
  fs.rmSync(root, { recursive: true, force: true });
}

// ── 6. a self-referencing icon key (the placeholder) does not count as an assignment ─────────────
{
  const root = mkMod();
  fs.writeFileSync(gfxOf(root), FOREIGN, "utf8");
  registerTechIconSprites(root, { infantry_weapons: "GFX_infantry_weapons_medium" });
  ok(fs.existsSync(gfxOf(root)), "the placeholder key must not trigger a delete of a foreign file");
  fs.rmSync(root, { recursive: true, force: true });
}

console.log(`test-research-managed-gfx: ${pass} assertions passed`);
